    public IEnumerator DecorateNow()
    {
#if UNITY_EDITOR
        if (calculating)
            yield break;
            
        calculating = true;
        float startTime = Time.realtimeSinceStartup;
        
        // Cache dimensions
        alphamapWidth = t.terrainData.alphamapWidth;
