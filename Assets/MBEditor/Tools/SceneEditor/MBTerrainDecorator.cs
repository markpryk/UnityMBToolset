    #region Slope Calculation
    
    /// <summary>
    /// Pre-calculate slope map for the terrain using Horn algorithm.
    /// Call this before decoration if using cached slope mode.
    /// </summary>
    public void PreCalculateSlopeMap()
    {
        if (t == null || t.terrainData == null) return;
        
        slopeCache = MBTerrainDecoratorSlopeExtensions.CachedSlopeMap.Create(
            t.terrainData, useJobSystem);
        
        Debug.Log($"[MBTerrainDecorator] Slope map pre-calculated: {slopeCache.Width}x{slopeCache.Height}");
    }
    
    /// <summary>
    /// Clear the cached slope map to free memory.
    /// </summary>
    public void ClearSlopeCache()
    {
        slopeCache = null;
    }
    
    /// <summary>
    /// Get slope at a normalized position using the configured method.
    /// </summary>
    /// <param name="normX">Normalized X position (0-1)</param>
    /// <param name="normY">Normalized Y position (0-1)</param>
    /// <returns>Slope value (degrees or normalized based on slopeInDegrees setting)</returns>
    public float GetSlopeAt(float normX, float normY)
    {
        if (!useAccurateSlope)
        {
            // Legacy Unity GetSteepness method
            return t.terrainData.GetSteepness(normY, normX) / (slopeInDegrees ? 1f : 90f);
        }
        
        if (cacheSlopeMap && slopeCache != null)
        {
            if (interpolateSlope)
                return slopeCache.GetSlopeAtInterpolated(normX, normY, slopeInDegrees);
            else
                return slopeCache.GetSlopeAt(normX, normY, slopeInDegrees);
        }
        
        // Direct calculation (slower but doesn't require pre-calculation)
        float[,] heights = t.terrainData.GetHeights(0, 0, heightMapWidth, heightMapHeight);
        float slope = MBTerrainDecoratorSlopeExtensions.CalculateSlopeAtNormalizedPosition(
            heights, normX, normY, cellSizeX, cellSizeY, heightScale);
        
        return slopeInDegrees ? slope : slope / 90f;
    }
    
    /// <summary>
    /// Calculate slope weight for decoration rules.
    /// </summary>
    public float CalculateSlopeWeight(float normX, float normY, float min, float max)
    {
        float slope = GetSlopeAt(normX, normY);
        return CalculateWeigth(slope, min, max, fallOffDistance / 100f);
    }
    
