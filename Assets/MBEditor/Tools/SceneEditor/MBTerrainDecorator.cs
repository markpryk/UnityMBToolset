    /// <summary>
    /// Prepare job data filtered by block type. If blockFilter is null, includes all layers.
    /// </summary>
    private void PrepareJobDataForBlock(LayerBlock? blockFilter,
        out NativeArray<RuleData> ruleData, 
        out NativeArray<int> layerRuleOffsets, out NativeArray<int> layerRuleCounts,
        out NativeArray<int> layerIndices, out NativeArray<bool> layerActive,
        out NativeArray<float> allRuleMaps, out NativeArray<int> ruleMapOffsets, 
        out NativeArray<int> ruleMapSizes)
    {
        var filteredLayers = blockFilter.HasValue 
            ? layers.Where(l => l.block == blockFilter.Value).ToList() 
            : layers;
        
        // Count total rules and map data
        int totalRules = 0;
        int totalMapSize = 0;
        
        foreach (var layer in filteredLayers)
        {
            totalRules += layer.rules.Count;
            foreach (var rule in layer.rules)
            {
                if (rule.map != null)
                    totalMapSize += rule.map.Length;
            }
        }
        
        int filteredCount = filteredLayers.Count();
        
        // Allocate arrays
        ruleData = new NativeArray<RuleData>(totalRules > 0 ? totalRules : 1, Allocator.TempJob);
        layerRuleOffsets = new NativeArray<int>(filteredCount > 0 ? filteredCount : 1, Allocator.TempJob);
        layerRuleCounts = new NativeArray<int>(filteredCount > 0 ? filteredCount : 1, Allocator.TempJob);
        layerIndices = new NativeArray<int>(filteredCount > 0 ? filteredCount : 1, Allocator.TempJob);
        layerActive = new NativeArray<bool>(filteredCount > 0 ? filteredCount : 1, Allocator.TempJob);
        allRuleMaps = new NativeArray<float>(totalMapSize > 0 ? totalMapSize : 1, Allocator.TempJob);
        ruleMapOffsets = new NativeArray<int>(totalRules > 0 ? totalRules : 1, Allocator.TempJob);
        ruleMapSizes = new NativeArray<int>(totalRules > 0 ? totalRules : 1, Allocator.TempJob);
        
        // Fill data
        int ruleIdx = 0;
        int mapOffset = 0;
        int l = 0;
        
        foreach (var layer in filteredLayers)
        {
            layerRuleOffsets[l] = ruleIdx;
            layerRuleCounts[l] = layer.rules.Count;
            layerIndices[l] = layer.layerIndex;
            layerActive[l] = layer.active;
            
            for (int r = 0; r < layer.rules.Count; r++)
            {
                var rule = layer.rules[r];
                
                ruleData[ruleIdx] = new RuleData
                {
                    active = rule.active,
                    invert = rule.invert,
                    filter = rule.filter,
                    blend = rule.blend,
                    min = rule.min,
                    max = rule.max,
                    frequency = rule.frequency,
                    lacunarity = rule.lacunarity,
                    perlinOctaves = rule.perlinOctaves,
                    intensity = rule.intensity,
                    contrast = rule.contrast,
                    targetLayerIndex = rule.targetLayerIndex,
                    imageChannel = rule.imageChannel,
                    curvatureType = (int)rule.curvatureType,
                    useShorelineDistance = rule.useShorelineDistance,
                    maxShorelineDistance = rule.maxShorelineDistance
                };
                
                if (rule.map != null && rule.map.Length > 0)
                {
                    ruleMapOffsets[ruleIdx] = mapOffset;
                    ruleMapSizes[ruleIdx] = rule.map.Length;
                    
                    for (int m = 0; m < rule.map.Length; m++)
                    {
                        // Extract channel based on imageChannel
                        float val = rule.imageChannel switch
                        {
                            ImageChannel.r => rule.map[m].r,
                            ImageChannel.g => rule.map[m].g,
                            ImageChannel.b => rule.map[m].b,
                            ImageChannel.a => rule.map[m].a,
                            _ => rule.map[m].r
                        };
                        allRuleMaps[mapOffset + m] = val;
                    }
                    
                    mapOffset += rule.map.Length;
                }
                else
                {
                    ruleMapOffsets[ruleIdx] = 0;
                    ruleMapSizes[ruleIdx] = 0;
                }
                
                ruleIdx++;
            }
            l++;
        }
    }
    
