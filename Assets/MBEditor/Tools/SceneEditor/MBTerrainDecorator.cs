    /// <summary>
    /// Check if any active rules use the waterLevel filter.
    /// </summary>
    private bool HasWaterLevelRules()
    {
        foreach (var layer in layers)
        {
            if (!layer.active) continue;
            foreach (var rule in layer.rules)
            {
                if (rule.active && rule.filter == FilterType.waterLevel)
                    return true;
            }
        }
        return false;
    }

    /// <summary>
    /// Calculate water-level-based decoration weight for the sequential path.
    /// Uses the cached water map if available, otherwise falls back to direct calculation.
    /// </summary>
    public float CalculateWaterLevelWeight(float normX, float normY, float min, float max,
                                            bool useShoreline, float maxShoreDist)
    {
        if (waterCache != null)
            return MBTerrainDecoratorWaterExtensions.CalculateWaterWeight(
                waterCache, normX, normY, min, max, fallOffDistance / 100f, useShoreline, maxShoreDist);

        // Fallback: direct calculation (no cache)
        float[,] h = t.terrainData.GetHeights(0, 0, heightMapWidth, heightMapHeight);
        return MBTerrainDecoratorWaterExtensions.CalculateWaterWeight(
            h, normX, normY, min, max, fallOffDistance / 100f,
            transform.position.y, heightScale, waterLevel);
    }

