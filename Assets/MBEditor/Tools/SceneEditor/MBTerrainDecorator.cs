    /// <summary>
    /// Pre-calculate curvature maps for the terrain
    /// Call this before decoration if using cached curvature mode.
    /// </summary>
    public void PreCalculateCurvatureMap()
    {
        if (t == null || t.terrainData == null) return;
        
        curvatureCache = MBTerrainDecoratorCurvatureExtensions.CachedCurvatureMap.Create(
            t.terrainData, useJobSystem);
        
        Debug.Log($"[MBTerrainDecorator] Curvature maps pre-calculated: {curvatureCache.Width}x{curvatureCache.Height}");
        Debug.Log($"  Standard range: [{curvatureCache.Statistics.MinStandard:F2}, {curvatureCache.Statistics.MaxStandard:F2}]");
        Debug.Log($"  Profile range: [{curvatureCache.Statistics.MinProfile:F2}, {curvatureCache.Statistics.MaxProfile:F2}]");
        Debug.Log($"  Plan range: [{curvatureCache.Statistics.MinPlan:F2}, {curvatureCache.Statistics.MaxPlan:F2}]");
    }
    
    /// <summary>
    /// Clear the cached curvature maps to free memory.
    /// </summary>
    public void ClearCurvatureCache()
    {
        curvatureCache = null;
    }
    
    /// <summary>
    /// Get curvature at a normalized position using the configured method.
    /// </summary>
    /// <param name="normX">Normalized X position (0-1)</param>
    /// <param name="normY">Normalized Y position (0-1)</param>
    /// <param name="type">Type of curvature to retrieve</param>
    /// <returns>Curvature value (normalized 0-1 or raw based on curvatureNormalized setting)</returns>
    public float GetCurvatureAt(float normX, float normY, CurvatureCalculator.CurvatureType type = CurvatureCalculator.CurvatureType.Standard)
    {
        if (!useAccurateCurvature)
        {
            // No legacy fallback for curvature - use cached or direct calculation
            return 0.5f; // Neutral value
        }
        
        if (cacheCurvatureMap && curvatureCache != null)
        {
            if (interpolateCurvature)
                return curvatureCache.GetCurvatureAtInterpolated(normX, normY, type, curvatureNormalized);
            else
                return curvatureCache.GetCurvatureAt(normX, normY, type, curvatureNormalized);
        }
        
        // Direct calculation (slower but doesn't require pre-calculation)
        float[,] heights = t.terrainData.GetHeights(0, 0, heightMapWidth, heightMapHeight);
        var result = CurvatureCalculator.CalculateAtNormalizedPosition(
            heights, normX, normY, cellSize, heightScale);
        
        float rawValue = result.Get(type);
        
        if (curvatureNormalized)
        {
            // Normalize using typical range (-50 to 50)
            return Mathf.Clamp01((rawValue + 50f) / 100f);
        }
        
        return rawValue;
    }
    
    /// <summary>
    /// Calculate curvature weight for decoration rules.
    /// </summary>
    public float CalculateCurvatureWeight(float normX, float normY, float min, float max, 
        CurvatureCalculator.CurvatureType type = CurvatureCalculator.CurvatureType.Standard)
    {
        float curvature = GetCurvatureAt(normX, normY, type);
        return CalculateWeigth(curvature, min, max, fallOffDistance / 100f);
    }
    
