    /// <summary>
    /// Burst-compiled job for processing terrain decoration in parallel.
    /// Uses NativeDisableParallelForRestriction since each pixel writes to a unique range.
    /// </summary>
    [BurstCompile(FloatPrecision.Standard, FloatMode.Fast)]
    public struct DecorateJob : IJobParallelFor
    {
        [ReadOnly] public int alphamapWidth;
        [ReadOnly] public int alphamapHeight;
        [ReadOnly] public int heightMapWidth;
        [ReadOnly] public int heightMapHeight;
        [ReadOnly] public int textureLayerCount;
        [ReadOnly] public float fallOffDistance;
        [ReadOnly] public NormalizationMode normMode;
        [ReadOnly] public float visibilityThreshold;
        
        // Slope calculation parameters
        [ReadOnly] public bool useAccurateSlope;
        [ReadOnly] public float cellSizeX;
        [ReadOnly] public float cellSizeY;
        [ReadOnly] public float heightScale;
        [ReadOnly] public bool slopeInDegrees;
        
        // Curvature calculation parameters
        [ReadOnly] public bool useAccurateCurvature;
        [ReadOnly] public float cellSize; // Average for curvature
        [ReadOnly] public bool curvatureNormalized;
        
        // Water level parameters
        [ReadOnly] public float waterLevel;
        [ReadOnly] public float terrainY;
        [ReadOnly] public NativeArray<float> waterShoreDistances;
        
        [ReadOnly] public NativeArray<float> heights;
        [ReadOnly] public NativeArray<float> slopes; // Pre-calculated slope map
        [ReadOnly] public NativeArray<float> curvatureStandard; // Pre-calculated curvature maps
        [ReadOnly] public NativeArray<float> curvatureProfile;
        [ReadOnly] public NativeArray<float> curvaturePlan;
        [ReadOnly] public NativeArray<float> existingSplatmaps;
        
        // Rule data - flattened for job access
        [ReadOnly] public NativeArray<RuleData> ruleData;
        [ReadOnly] public NativeArray<int> layerRuleOffsets;
        [ReadOnly] public NativeArray<int> layerRuleCounts;
        [ReadOnly] public NativeArray<int> layerIndices;
        [ReadOnly] public NativeArray<bool> layerActive;
        
        // Rule maps - all concatenated
        [ReadOnly] public NativeArray<float> allRuleMaps;
        [ReadOnly] public NativeArray<int> ruleMapOffsets;
        [ReadOnly] public NativeArray<int> ruleMapSizes;
        
        // Output - disable safety restriction since each pixel writes to unique indices
        [NativeDisableContainerSafetyRestriction]
        public NativeArray<float> outputSplatmap;
        
        public void Execute(int pixelIndex)
        {
            int x = pixelIndex % alphamapWidth;
            int y = pixelIndex / alphamapWidth;
            
            float normX = x / (float)(alphamapWidth - 1);
            float normY = y / (float)(alphamapHeight - 1);
            
            // Use stack-allocated array for small fixed-size data (max 32 layers)
            const int MAX_LAYERS = 32;
            var rawWeights = new NativeArray<float>(math.min(textureLayerCount, MAX_LAYERS), Allocator.Temp);
            
            // Zero initialize
            for (int i = 0; i < rawWeights.Length; i++)
                rawWeights[i] = 0f;
            
            int decoratorLayerCount = layerActive.Length;
            for (int layerNo = 0; layerNo < decoratorLayerCount; layerNo++)
            {
                if (!layerActive[layerNo]) continue;
                int targetIdx = layerIndices[layerNo];
                if (targetIdx >= textureLayerCount || targetIdx >= rawWeights.Length) continue;
                
                float layerWeight = ProcessLayerRules(layerNo, x, y, normX, normY);
                rawWeights[targetIdx] += layerWeight;
            }
            
            // Convert to splatmap weights and write directly to output
            ConvertAndWriteSplatmapWeights(rawWeights, pixelIndex);
            
            rawWeights.Dispose();
        }
        
        private float ProcessLayerRules(int layerNo, int x, int y, float normX, float normY)
        {
            int ruleOffset = layerRuleOffsets[layerNo];
            int ruleCount = layerRuleCounts[layerNo];
            
            float layerResultWeight = 0f;
            bool firstRule = true;
            
            for (int i = 0; i < ruleCount; i++)
            {
                RuleData rule = ruleData[ruleOffset + i];
                if (!rule.active) continue;
                
                float weight = EvaluateRule(rule, ruleOffset + i, x, y, normX, normY);
                
                // Apply intensity and contrast
                if (rule.intensity < 0)
                    weight = 1 - weight;
                
                weight = (weight - 0.5f) * (rule.contrast + 1) + 0.5f;
                weight *= math.abs(rule.intensity);
                weight = math.clamp(weight, 0, 1);
                
                // Apply blend
                if (firstRule)
                {
                    layerResultWeight = weight;
                    firstRule = false;
                }
                else
                {
                    layerResultWeight = ApplyBlend(layerResultWeight, weight, rule.blend);
                }
            }
            
            return math.clamp(layerResultWeight, 0f, 1f);
        }
        
        private float EvaluateRule(RuleData rule, int globalRuleIndex, int x, int y, float normX, float normY)
        {
            float weight = 0f;
            
            switch (rule.filter)
            {
                case FilterType.height:
                    int hx = math.clamp((int)(normX * (heightMapHeight - 1)), 0, heightMapHeight - 1);
                    int hy = math.clamp((int)(normY * (heightMapWidth - 1)), 0, heightMapWidth - 1);
                    float heightVal = heights[hx * heightMapWidth + hy];
                    weight = CalculateWeight(heightVal, rule.min, rule.max, fallOffDistance / 100f);
                    break;
                    
                case FilterType.slope:
                    weight = CalculateSlopeWeightBurst(normX, normY, rule.min, rule.max);
                    break;
                    
                case FilterType.curvature:
                    weight = CalculateCurvatureWeightBurst(normX, normY, rule.min, rule.max, rule.curvatureType);
                    break;
                    
                case FilterType.noise:
                    weight = ProPerlinBurst(normY, normX, rule.frequency, rule.lacunarity, rule.perlinOctaves);
                    break;
                    
                case FilterType.texture:
                case FilterType.pgm:
                case FilterType.generator:
                case FilterType.warband:
                    int mapOffset = ruleMapOffsets[globalRuleIndex];
                    int mapSize = ruleMapSizes[globalRuleIndex];
                    if (mapSize > 0)
                    {
                        int idx = x + y * alphamapWidth;
                        if (idx < mapSize)
                        {
                            weight = allRuleMaps[mapOffset + idx];
                        }
                    }
                    break;
                    
                case FilterType.layer:
                    if (rule.targetLayerIndex < textureLayerCount)
                    {
                        int splatIdx = (x + y * alphamapWidth) * textureLayerCount + rule.targetLayerIndex;
                        if (splatIdx < existingSplatmaps.Length)
                        {
                            weight = existingSplatmaps[splatIdx];
                        }
                    }
                    break;
                    
                case FilterType.waterLevel:
                    weight = CalculateWaterWeightBurst(normX, normY, rule.min, rule.max,
                                                       rule.useShorelineDistance, rule.maxShorelineDistance);
                    break;
                
            }
            if (rule.invert)
                weight = 1f - weight;
            
            return weight;
        }
        
        private float CalculateWaterWeightBurst(float normX, float normY, float min, float max,
                                                  bool useShoreline, float maxShoreDist)
        {
            // Use pre-calculated shoreline distances if available
            NativeArray<float> shores = (useShoreline && waterShoreDistances.IsCreated && waterShoreDistances.Length > 0)
                ? waterShoreDistances : default;
            
            return MBTerrainDecoratorWaterExtensions.CalculateWaterWeightWithShorelineBurst(
                heights, shores,
                heightMapWidth, heightMapHeight,
                normX, normY,
                min, max, fallOffDistance / 100f,
                terrainY, heightScale, waterLevel,
                useShoreline ? maxShoreDist : 0f);
        }
        
        private float CalculateSlopeWeightBurst(float normX, float normY, float min, float max)
        {
            float slope;
            
            if (useAccurateSlope && slopes.IsCreated && slopes.Length > 0)
            {
                // Use pre-calculated slope map
                int sx = math.clamp((int)(normX * (heightMapWidth - 1)), 0, heightMapWidth - 1);
                int sy = math.clamp((int)(normY * (heightMapHeight - 1)), 0, heightMapHeight - 1);
                slope = slopes[sy * heightMapWidth + sx];
                
                // Convert to normalized if needed
                if (!slopeInDegrees)
                    slope = slope / 90f;
            }
            else
            {
                // Fallback: calculate slope directly using Horn's algorithm
                slope = MBTerrainDecoratorSlopeExtensions.CalculateSlopeBurst(
                    heights, heightMapWidth, heightMapHeight,
                    normX, normY, cellSizeX, cellSizeY, heightScale);
                
                if (!slopeInDegrees)
                    slope = slope / 90f;
            }
            
            return CalculateWeight(slope, min, max, fallOffDistance / 100f);
        }
        
        private float CalculateCurvatureWeightBurst(float normX, float normY, float min, float max, int curvatureType)
        {
            float curvature;
            
            // Select appropriate curvature map
            NativeArray<float> curvatureMap;
            switch (curvatureType)
            {
                case 1: // Profile
                    curvatureMap = curvatureProfile;
                    break;
                case 2: // Plan
                    curvatureMap = curvaturePlan;
                    break;
                default: // Standard
                    curvatureMap = curvatureStandard;
                    break;
            }
            
            if (useAccurateCurvature && curvatureMap.IsCreated && curvatureMap.Length > 0)
            {
                // Use pre-calculated curvature map (already normalized)
                int cx = math.clamp((int)(normY * (heightMapWidth - 1)), 0, heightMapWidth - 1);
                int cy = math.clamp((int)(normX * (heightMapHeight - 1)), 0, heightMapHeight - 1);
                curvature = curvatureMap[cy * heightMapWidth + cx];
            }
            else
            {
                // Fallback: calculate curvature directly
                curvature = MBTerrainDecoratorCurvatureExtensions.CalculateCurvatureWeightBurst(
                    heights, heightMapWidth, heightMapHeight,
                    normX, normY, 0f, 1f, 0.0001f,
                    cellSize, heightScale, curvatureType);
            }
            
            return CalculateWeight(curvature, min, max, fallOffDistance / 100f);
        }
        
        private float CalculateWeight(float val, float min, float max, float falloff)
        {
            if (falloff < 0.0001f) falloff = 0.0001f;
            
            float weight;
            if (val > min + falloff / 2f && val <= max - falloff / 2f)
            {
                weight = 1f;
            }
            else if (val < min + falloff / 2f)
            {
                weight = (val - (min - falloff / 2f)) / falloff;
            }
            else
            {
                weight = 1f - (val - (max - falloff / 2f)) / falloff;
            }
            
            return math.clamp(weight, 0f, 1f);
        }
        
        private float ProPerlinBurst(float x, float y, float frequency, float lacunarity, int octaves)
        {
            float total = 0;
            float freq = frequency;
            float amplitude = 1f;
            float persistence = 0.5f;
            float totalAmplitude = 0;
            
            for (int i = 0; i < octaves; i++)
            {
                // Use Unity.Mathematics noise
                float noiseVal = noise.cnoise(new Unity.Mathematics.float2(x * freq, y * freq));
                total += (noiseVal * 0.5f + 0.5f) * amplitude;
                totalAmplitude += amplitude;
                amplitude *= persistence;
                freq *= lacunarity;
            }
            
            return total / math.max(totalAmplitude, 0.0001f);
        }
        
        private float ApplyBlend(float current, float newVal, BlendType blend)
        {
            switch (blend)
            {
                case BlendType.normal: return newVal; 
                case BlendType.add: return current + newVal;
                case BlendType.sub: return current - newVal;
                case BlendType.mul: return current * newVal;
                case BlendType.min: return math.min(current, newVal);
                case BlendType.max: return math.max(current, newVal);
                case BlendType.occlusion:
                    float occluded = current * (1f - newVal);
                    return math.clamp(occluded + newVal, 0, 1);
                default: return current;
            }
        }
        
        private void ConvertAndWriteSplatmapWeights(NativeArray<float> rawWeights, int pixelIndex)
        {
            int count = rawWeights.Length;
            int outputOffset = pixelIndex * textureLayerCount;
            
            switch (normMode)
            {
                case NormalizationMode.SimpleNormalize:
                {
                    float total = 0f;
                    for (int i = 0; i < count; i++)
                        total += rawWeights[i];
                    
                    if (total > 0.0001f)
                    {
                        for (int i = 0; i < count; i++)
                            outputSplatmap[outputOffset + i] = rawWeights[i] / total;
                    }
                    else
                    {
                        // Default to first layer
                        // outputSplatmap[outputOffset] = 1f;
                        for (int i = 1; i < count; i++)
                            outputSplatmap[outputOffset + i] = 0f;
                    }
                    break;
                }
                    
                case NormalizationMode.MBPainterAlgorithm:
                {
                    WriteMBPainterWeights(rawWeights, outputOffset);
                    break;
                }
                    
                case NormalizationMode.MBNormalized:
                {
                    // First apply painter algorithm to temp storage
                    var painted = new NativeArray<float>(count, Allocator.Temp);
                    ApplyMBPainterToArray(rawWeights, painted);
                    
                    // Then normalize
                    float paintedTotal = 0f;
                    for (int i = 0; i < count; i++)
                        paintedTotal += painted[i];
                    
                    if (paintedTotal > 0.0001f)
                    {
                        for (int i = 0; i < count; i++)
                            outputSplatmap[outputOffset + i] = painted[i] / paintedTotal;
                    }
                    else
                    {
                        outputSplatmap[outputOffset] = 1f;
                        for (int i = 1; i < count; i++)
                            outputSplatmap[outputOffset + i] = 0f;
                    }
                    
                    painted.Dispose();
                    break;
                }
                    
                case NormalizationMode.RawPassthrough:
                {
                    // Write raw weights directly - no normalization
                    for (int i = 0; i < count; i++)
                        outputSplatmap[outputOffset + i] = rawWeights[i];
                    break;
                }
            }
        }
        
        private void WriteMBPainterWeights(NativeArray<float> input, int outputOffset)
        {
            int count = input.Length;
            
            for (int i = 0; i < count; i++)
            {
                if (input[i] < visibilityThreshold)
                {
                    outputSplatmap[outputOffset + i] = 0f;
                    continue;
                }
                
                float visibility = input[i];
                
                for (int j = i + 1; j < count; j++)
                {
                    visibility *= (1f - input[j]);
                    if (visibility < visibilityThreshold)
                    {
                        visibility = 0f;
                        break;
                    }
                }
                
                outputSplatmap[outputOffset + i] = visibility;
            }
        }
        
        private void ApplyMBPainterToArray(NativeArray<float> input, NativeArray<float> output)
        {
            int count = input.Length;
            
            for (int i = 0; i < count; i++)
            {
                if (input[i] < visibilityThreshold)
                {
                    output[i] = 0f;
                    continue;
                }
                
                float visibility = input[i];
                
                for (int j = i + 1; j < count; j++)
                {
                    visibility *= (1f - input[j]);
                    if (visibility < visibilityThreshold)
                    {
                        visibility = 0f;
                        break;
                    }
                }
                
                output[i] = visibility;
            }
        }
    }
    
