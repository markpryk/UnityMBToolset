    public float ProPerlin(float x, float y, float frequency, float lacunarity,int perlinOctaves)
    {
        float total = 0;
        float _frequency = frequency;
        float amplitude = 1f;
        float persistence = 0.5f;
        float totalAmplitude = 0;
        
        for (int i = 0; i < perlinOctaves; i++)
        {
            total += Mathf.PerlinNoise(x * _frequency, y * _frequency) * amplitude;
            totalAmplitude += amplitude;
            amplitude *= persistence;
            _frequency *= lacunarity;
        }
        
        return total / totalAmplitude;
    }
    
    public float[] ApplyMBPainterAlgorithm(float[] layerIntensities)
    {
        int count = layerIntensities.Length;
        float[] visibilities = new float[count];
        
        for (int i = 0; i < count; i++)
        {
            if (layerIntensities[i] < visibilityThreshold)
            {
                visibilities[i] = 0f;
                continue;
            }
            
            float visibility = layerIntensities[i];
            
            for (int j = i + 1; j < count; j++)
            {
                visibility *= (1f - layerIntensities[j]);
                
                if (visibility < visibilityThreshold)
                {
                    visibility = 0f;
                    break;
                }
            }
            
            visibilities[i] = visibility;
        }
        
        return visibilities;
    }
    
    public float[] ConvertToSplatmapWeights(float[] rawWeights)
    {
        int count = rawWeights.Length;
        float[] result = new float[count];
        
        switch (normalizationMode)
        {
            case NormalizationMode.SimpleNormalize:
                float total = 0f;
                for (int i = 0; i < count; i++)
                    total += rawWeights[i];
                
                if (total > 0.0001f)
                {
                    for (int i = 0; i < count; i++)
                        result[i] = rawWeights[i] / total;
                }
                break;
                
            case NormalizationMode.MBPainterAlgorithm:
                result = ApplyMBPainterAlgorithm(rawWeights);
                break;
                
            case NormalizationMode.MBNormalized:
                float[] painted = ApplyMBPainterAlgorithm(rawWeights);
                float paintedTotal = 0f;
                for (int i = 0; i < count; i++)
                    paintedTotal += painted[i];
                
                if (paintedTotal > 0.0001f)
                {
                    for (int i = 0; i < count; i++)
                        result[i] = painted[i] / paintedTotal;
                }
                break;
        }
        
        return result;
    }
    
    public float ApplyOcclusionBlend(float currentWeight, float newWeight, float intensity)
    {
        float occludedOld = currentWeight * (1f - newWeight * intensity);
        float addedNew = newWeight * intensity;
        return Mathf.Clamp01(occludedOld + addedNew);
    }
    
