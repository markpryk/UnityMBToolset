    private IEnumerator DecorateSequential()
    {
        // Cache data
        float[,] heights = t.terrainData.GetHeights(0, 0, heightMapWidth, heightMapHeight);
        map = new float[alphamapWidth, alphamapHeight, textureLayerCount];
        
        UnityEngine.Random.InitState(42);
        
        bool hasBaseLayers = HasActiveBaseLayers();
        bool hasOverlayLayers = HasActiveOverlayLayers();
        
        // PASS 1: BASE BLOCK - Engine-accurate generator layers
        if (hasBaseLayers)
        {
            for (int y = 0; y < alphamapHeight; y++)
            {
                if (y % progressUpdateInterval == 0)
                {
                    float progress = y / (float)alphamapHeight * (hasOverlayLayers ? 0.5f : 1f);
                    EditorUtility.DisplayProgressBar("Decorating", $"Base block: row {y}/{alphamapHeight}", progress);
                    
                    if (showProgress)
                    {
                        calculatingPercent = progress;
                        t.terrainData.SetAlphamaps(0, 0, map);
                        yield return null;
                    }
                }
                
                for (int x = 0; x < alphamapWidth; x++)
                {
                    float normX = x / (float)(alphamapWidth - 1);
                    float normY = y / (float)(alphamapHeight - 1);
                    
                    float[] rawWeights = new float[textureLayerCount];
                    
                    ProcessLayersForBlock(heights, normX, normY, x, y, LayerBlock.Base);
                    
                    for (int layerNo = 0; layerNo < layers.Count; layerNo++)
                    {
                        if (!layers[layerNo].active) continue;
                        if (layers[layerNo].block != LayerBlock.Base) continue;
                        if (layers[layerNo].layerIndex >= textureLayerCount) continue;
                        
                        rawWeights[layers[layerNo].layerIndex] += layers[layerNo].resultWeight;
                    }
                    
                    float[] splatWeights = ConvertToSplatmapWeights(rawWeights);
                    
                    for (int i = 0; i < textureLayerCount; i++)
                        map[x, y, i] = splatWeights[i];
                }
            }
        }
        
        // PASS 2: OVERLAY BLOCK - Hand-painted layers over base
        if (hasOverlayLayers)
        {
            bool hasVegMask = HasVegetationMask();
            
            for (int y = 0; y < alphamapHeight; y++)
            {
                if (y % progressUpdateInterval == 0)
                {
                    float progress = 0.5f + (y / (float)alphamapHeight * 0.5f);
                    EditorUtility.DisplayProgressBar("Decorating", $"Overlay block: row {y}/{alphamapHeight}", progress);
                    
                    if (showProgress)
                    {
                        calculatingPercent = progress;
                        t.terrainData.SetAlphamaps(0, 0, map);
                        yield return null;
                    }
                }
                
                for (int x = 0; x < alphamapWidth; x++)
                {
                    float normX = x / (float)(alphamapWidth - 1);
                    float normY = y / (float)(alphamapHeight - 1);
                    
                    // Vegetation mask: attenuate all overlay weights at this pixel
                    float vegMultiplier = hasVegMask ? (1f - GetVegetationMaskAt(x, y)) : 1f;
                    
                    ProcessLayersForBlock(heights, normX, normY, x, y, LayerBlock.Overlay);
                    
                    float[] baseWeights = new float[textureLayerCount];
                    for (int i = 0; i < textureLayerCount; i++)
                        baseWeights[i] = map[x, y, i];
                    
                    for (int layerNo = 0; layerNo < layers.Count; layerNo++)
                    {
                        if (!layers[layerNo].active) continue;
                        if (layers[layerNo].block != LayerBlock.Overlay) continue;
                        if (layers[layerNo].layerIndex >= textureLayerCount) continue;
                        
                        float overlayWeight = layers[layerNo].resultWeight * layers[layerNo].overlayOpacity * vegMultiplier;
                        if (overlayWeight < visibilityThreshold) continue;
                        
                        ApplyOverlayToBaseWeights(baseWeights, layers[layerNo].layerIndex, 
                            overlayWeight, layers[layerNo].overlayBlendMode);
                    }
                    
                    if (renormalizeAfterOverlay)
                    {
                        float total = 0f;
                        for (int i = 0; i < textureLayerCount; i++)
                            total += baseWeights[i];
                        if (total > 0.0001f)
                            for (int i = 0; i < textureLayerCount; i++)
                                baseWeights[i] /= total;
                    }
                    
                    for (int i = 0; i < textureLayerCount; i++)
                        map[x, y, i] = baseWeights[i];
                }
            }
        }
        
        t.terrainData.SetAlphamaps(0, 0, map);
    }
    
    /// <summary>
    /// Process layers belonging to a specific block for a single pixel.
    /// </summary>
    private void ProcessLayersForBlock(float[,] heights, float normX, float normY, int x, int y, LayerBlock block)
    {
        for (int layerNo = 0; layerNo < layers.Count; layerNo++)
        {
            if (!layers[layerNo].active) continue;
            if (layers[layerNo].block != block) continue;
            
            float layerResultWeight = 0f;
            bool firstRule = true;
            
            for (int i = 0; i < layers[layerNo].rules.Count; i++)
            {
                if (!layers[layerNo].rules[i].active) continue;
                
                float weight = 0f;
                var rule = layers[layerNo].rules[i];
                
                switch (rule.filter)
                {
                    case FilterType.height:
                        int hx = Mathf.FloorToInt(normY * (heightMapHeight - 1));
                        int hy = Mathf.FloorToInt(normX * (heightMapWidth - 1));
                        float heightVal = heights[hx, hy];
                        weight = CalculateWeigth(heightVal, rule.min, rule.max, fallOffDistance / 100f);
                        break;
                    case FilterType.slope:
                        weight = CalculateSlopeWeight(normX, normY, rule.min, rule.max);
                        break;
                    case FilterType.curvature:
                        weight = CalculateCurvatureWeight(normX, normY, rule.min, rule.max, rule.curvatureType);
                        break;
                    case FilterType.noise:
                        weight = ProPerlin(normX, normY, rule.frequency, rule.lacunarity, rule.perlinOctaves);
                        break;
                    case FilterType.texture:
                    case FilterType.pgm:
                    case FilterType.generator:
                        if (rule.map != null && rule.map.Length > 0)
                        {
                            int idx = x + y * alphamapWidth;
                            if (idx < rule.map.Length)
                            {
                                Color c = rule.map[idx];
                                weight = rule.imageChannel switch
                                {
                                    ImageChannel.r => c.r, ImageChannel.g => c.g,
                                    ImageChannel.b => c.b, ImageChannel.a => c.a, _ => c.r
                                };
                            }
                        }
                        break;
                    case FilterType.layer:
                        if (rule.targetLayerIndex < textureLayerCount)
                            weight = GetWeight(rule.targetLayerIndex, x, y);
                        break;
                    case FilterType.waterLevel:
                        weight = CalculateWaterLevelWeight(normX, normY, rule.min, rule.max,
                                                           rule.useShorelineDistance, rule.maxShorelineDistance);
                        break;
                }
                
                if (rule.intensity < 0) weight = 1 - weight;
                
                if (rule.invert)
                    weight = 1f - weight;
                
                weight = (weight - 0.5f) * (rule.contrast + 1) + 0.5f;
                weight *= Mathf.Abs(rule.intensity);
                weight = Mathf.Clamp(weight, 0, 1);
                rule.weight = weight;
                
                if (firstRule) { layerResultWeight = weight; firstRule = false; }
                else
                {
                    layerResultWeight = rule.blend switch
                    {
                        BlendType.normal => weight,
                        BlendType.add => layerResultWeight + weight,
                        BlendType.sub => layerResultWeight - weight,
                        BlendType.mul => layerResultWeight * weight,
                        BlendType.min => Mathf.Min(layerResultWeight, weight),
                        BlendType.max => Mathf.Max(layerResultWeight, weight),
                        BlendType.occlusion => ApplyOcclusionBlend(layerResultWeight, weight, 1f),
                        _ => layerResultWeight
                    };
                }
            }
            layers[layerNo].resultWeight = Mathf.Clamp(layerResultWeight, 0f, 1f);
        }
    }
    
    /// <summary>
    /// Apply overlay layer weight onto base splatmap weights.
    /// </summary>
    private void ApplyOverlayToBaseWeights(float[] baseWeights, int targetIdx, float overlayWeight, OverlayBlendMode mode)
    {
        switch (mode)
        {
            case OverlayBlendMode.Additive:
                baseWeights[targetIdx] += overlayWeight;
                break;
                
            case OverlayBlendMode.Lerp:
                for (int i = 0; i < baseWeights.Length; i++)
                {
                    float target = (i == targetIdx) ? 1f : 0f;
                    baseWeights[i] = Mathf.Lerp(baseWeights[i], target, overlayWeight);
                }
                break;
                
            case OverlayBlendMode.Replace:
                float scaleDown = 1f - overlayWeight;
                for (int i = 0; i < baseWeights.Length; i++)
                {
                    if (i == targetIdx) baseWeights[i] = overlayWeight;
                    else baseWeights[i] *= scaleDown;
                }
                break;
                
            case OverlayBlendMode.PainterOcclusion:
                float remaining = 1f - overlayWeight;
                for (int i = 0; i < baseWeights.Length; i++)
                {
                    if (i == targetIdx) baseWeights[i] = baseWeights[i] * remaining + overlayWeight;
                    else baseWeights[i] *= remaining;
                }
                break;
        }
    }
    
    private void ProcessLayersOptimized(float[,] heights, float normX, float normY, int x, int y)
    {
        for (int layerNo = 0; layerNo < layers.Count; layerNo++)
        {
            if (!layers[layerNo].active) continue;
            
            float layerResultWeight = 0f;
            bool firstRule = true;
            
            for (int i = 0; i < layers[layerNo].rules.Count; i++)
            {
                if (!layers[layerNo].rules[i].active) continue;
                
                float weight = 0f;
                var rule = layers[layerNo].rules[i];
                
                switch (rule.filter)
                {
                    case FilterType.height:
                        int hx = Mathf.FloorToInt(normY * (heightMapHeight - 1));
                        int hy = Mathf.FloorToInt(normX * (heightMapWidth - 1));
                        float heightVal = heights[hx, hy];
                        weight = CalculateWeigth(heightVal, rule.min, rule.max, fallOffDistance / 100f);
                        break;
                        
                    case FilterType.slope:
                        // Use proper slope calculation
                        weight = CalculateSlopeWeight(normX, normY, rule.min, rule.max);
                        break;
                        
                    case FilterType.curvature:
                        // Use proper curvature calculation
                        weight = CalculateCurvatureWeight(normX, normY, rule.min, rule.max, rule.curvatureType);
                        break;
                        
                    case FilterType.noise:
                        weight = ProPerlin(normX, normY, rule.frequency, rule.lacunarity,rule.perlinOctaves);
                        break;
                        
                    case FilterType.texture:
                    case FilterType.pgm:
                    case FilterType.generator:
                        if (rule.map != null && rule.map.Length > 0)
                        {
                            int idx = x + y * alphamapWidth;
                            if (idx < rule.map.Length)
                            {
                                Color c = rule.map[idx];
                                weight = rule.imageChannel switch
                                {
                                    ImageChannel.r => c.r,
                                    ImageChannel.g => c.g,
                                    ImageChannel.b => c.b,
                                    ImageChannel.a => c.a,
                                    _ => c.r
                                };
                            }
                        }
                        break;
                        
                    case FilterType.layer:
                        if (rule.targetLayerIndex < textureLayerCount)
                        {
                            weight = GetWeight(rule.targetLayerIndex, x, y);
                        }
                        break;
                    case FilterType.waterLevel:
                        weight = CalculateWaterLevelWeight(normX, normY, rule.min, rule.max,
                                                           rule.useShorelineDistance, rule.maxShorelineDistance);
                        break;
                }
                
                if (rule.intensity < 0)
                    weight = 1 - weight;
                
                if (rule.invert)
                    weight = 1f - weight;
                
                weight = (weight - 0.5f) * (rule.contrast + 1) + 0.5f;
                weight *= Mathf.Abs(rule.intensity);
                weight = Mathf.Clamp(weight, 0, 1);
                
                rule.weight = weight;
                
                if (firstRule)
                {
                    layerResultWeight = weight;
                    firstRule = false;
                }
                else
                {
                    layerResultWeight = rule.blend switch
                    {
                        BlendType.normal => weight,
                        BlendType.add => layerResultWeight + weight,
                        BlendType.sub => layerResultWeight - weight,
                        BlendType.mul => layerResultWeight * weight,
                        BlendType.min => Mathf.Min(layerResultWeight, weight),
                        BlendType.max => Mathf.Max(layerResultWeight, weight),
                        BlendType.occlusion => ApplyOcclusionBlend(layerResultWeight, weight, 1f),
                        _ => layerResultWeight
                    };
                }
            }
            
            layers[layerNo].resultWeight = Mathf.Clamp(layerResultWeight, 0f, 1f);
        }
    }
    
    private void ProcessTrees()
    {
        UnityEngine.Random.InitState(42);
        
        for (int y = 0; y < alphamapHeight; y++)
        {
            for (int x = 0; x < alphamapWidth; x++)
            {
                float normX = x / (float)(alphamapWidth - 1);
                float normY = y / (float)(alphamapHeight - 1);
                
                for (int layerNo = 0; layerNo < layers.Count; layerNo++)
                {
                    if (!layers[layerNo].active) continue;
                    if (layers[layerNo].layerIndex < textureLayerCount) continue;
                    
                    float probability = UnityEngine.Random.Range(0f, 1f);
                    int inc = Mathf.CeilToInt(alphamapWidth / Mathf.Sqrt(layers[layerNo].maximumTreeCount));
                    
                    if (y % inc == 0 && x % inc == 0)
                    {
                        if (layers[layerNo].treeCount < layers[layerNo].maximumTreeCount)
                        {
                            if (layers[layerNo].resultWeight > 0)
                            {
                                int treeIdx = layers[layerNo].layerIndex - textureLayerCount;
                                if (treeIdx >= 0 && treeIdx < treePrototypeCount)
                                {
                                    if (probability < layers[layerNo].probability * layers[layerNo].resultWeight)
                                    {
                                        TreeInstance tree = new TreeInstance();
                                        
                                        float rndPos = UnityEngine.Random.Range(-1f, 1f) / alphamapWidth * 
                                                       layers[layerNo].randomPosition * inc;
                                        float rndRot = UnityEngine.Random.Range(-1f, 1f) * layers[layerNo].randomRotation * 6.283f;
                                        float rndScale = 1f + UnityEngine.Random.Range(0, 1f) * layers[layerNo].randomSize;
                                        
                                        float nx = normY + rndPos;
                                        float ny = normX + rndPos;
                                        
                                        float _height = t.terrainData.GetHeight(
                                            Mathf.FloorToInt(ny * (heightMapHeight - 1)),
                                            Mathf.FloorToInt(nx * (heightMapWidth - 1)));
                                        
                                        tree.position = new Vector3(ny, 
                                            (_height + layers[layerNo].offset) / t.terrainData.heightmapScale.y, nx);
                                        tree.color = Color.Lerp(Color.white, new Color(1, 0.8f, 0), 
                                            UnityEngine.Random.Range(0f, layers[layerNo].randomHealth));
                                        tree.rotation = rndRot;
                                        tree.heightScale = layers[layerNo].height * rndScale;
                                        tree.widthScale = layers[layerNo].width * rndScale;
                                        tree.prototypeIndex = treeIdx;
                                        tree.lightmapColor = Color.white;
                                        layers[layerNo].treeCount++;
                                        t.AddTreeInstance(tree);
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
    }
    
