        if (clearTrees)
        {
            treePrototypeCount = t.terrainData.treePrototypes.Length;
            t.terrainData.treeInstances = new TreeInstance[0];
        }
        
        // Process filter maps
        ProcessGeneratorFilters();
        ProcessPGMFilters();
        ProcessTextureFilters();
        ProcessWarbandFilters();
        
        // Pre-calculate slope map if using accurate slope and caching
        if (useAccurateSlope && cacheSlopeMap && HasSlopeRules())
        {
            EditorUtility.DisplayProgressBar("Prepare", "Calculating slope map...", 0f);
            PreCalculateSlopeMap();
        }
        
        // Pre-calculate curvature maps if using accurate curvature and caching
        if (useAccurateCurvature && cacheCurvatureMap && HasCurvatureRules())
        {
            EditorUtility.DisplayProgressBar("Prepare", "Calculating curvature maps...", 0.1f);
            PreCalculateCurvatureMap();
        }
        
        // Pre-calculate water level and shoreline distance map if needed
        if (cacheWaterMap && HasWaterLevelRules())
        {
            EditorUtility.DisplayProgressBar("Prepare", "Calculating water level map...", 0.2f);
            PreCalculateWaterMap();
        }
        
        // Initialize layers
        InitializeLayers();
        
        // Bake vegetation mask texture if assigned
        // BakeVegetationMask();
        
        if (useJobSystem)
        {
            yield return StartCoroutine(DecorateWithJobs());
        }
        else
        {
            yield return StartCoroutine(DecorateSequential());
        }
        
        // Process trees (not parallelized - needs random state)
        if (clearTrees)
        {
            ProcessTrees();
        }
        
        // Cleanup
        DisposeNativeArrays();
        
        // Clear caches if not persistent
        if (!cacheSlopeMap)
        {
            ClearSlopeCache();
        }
        if (!cacheCurvatureMap)
        {
            ClearCurvatureCache();
        }
        if (!cacheWaterMap)
        {
            ClearWaterCache();
        }
        
        EditorUtility.ClearProgressBar();
        t.Flush();
        
        Debug.Log($"Decoration completed in {Time.realtimeSinceStartup - startTime:F2}s " +
                  $"(Mode: {normalizationMode}, Jobs: {useJobSystem}, AccurateSlope: {useAccurateSlope}, AccurateCurvature: {useAccurateCurvature})");
        
        calculating = false;
#else
        yield break;
#endif
    }
    
    /// <summary>
    /// Check if any active rules use slope filter.
    /// </summary>
    private bool HasSlopeRules()
    {
        foreach (var layer in layers)
        {
            if (!layer.active) continue;
            foreach (var rule in layer.rules)
            {
                if (rule.active && rule.filter == FilterType.slope)
                    return true;
            }
        }
        return false;
    }
    
    /// <summary>
    /// Check if any active rules use curvature filter.
    /// </summary>
    private bool HasCurvatureRules()
    {
        foreach (var layer in layers)
        {
            if (!layer.active) continue;
            foreach (var rule in layer.rules)
            {
                if (rule.active && rule.filter == FilterType.curvature)
                    return true;
            }
        }
        return false;
    }
    
    private void InitializeLayers()
    {
        for (int layerNo = 0; layerNo < layers.Count; layerNo++)
        {
            layers[layerNo].activeRuleCount = 0;
            layers[layerNo].debugResultWeight = 0;
            layers[layerNo].resultWeight = 0;
            layers[layerNo].correctedResultWeight = 0;
            layers[layerNo].debugCorrectedResultWeight = 0;
            layers[layerNo].treeCount = 0;
            
            for (int i = 0; i < layers[layerNo].rules.Count; i++)
            {
                layers[layerNo].rules[i].debugWeight = 0f;
                if (layers[layerNo].rules[i].active)
                    layers[layerNo].activeRuleCount++;
                layers[layerNo].rules[i].weight = 0f;
            }
        }
    }
    
    private IEnumerator DecorateWithJobs()
    {
        int totalPixels = alphamapWidth * alphamapHeight;
        bool hasBaseLayers = HasActiveBaseLayers();
        bool hasOverlayLayers = HasActiveOverlayLayers();
        
        // Allocate shared native arrays
        cachedHeights = new NativeArray<float>(heightMapWidth * heightMapHeight, Allocator.TempJob);
        cachedSplatmaps = new NativeArray<float>(totalPixels * textureLayerCount, Allocator.TempJob);
        outputSplatmap = new NativeArray<float>(totalPixels * textureLayerCount, Allocator.TempJob);
        
        // Cache height data
        float[,] heights = t.terrainData.GetHeights(0, 0, heightMapWidth, heightMapHeight);
        for (int y = 0; y < heightMapHeight; y++)
            for (int x = 0; x < heightMapWidth; x++)
                cachedHeights[y * heightMapWidth + x] = heights[y, x];
        
        // Cache existing splatmaps
        float[,,] splatmaps = t.terrainData.GetAlphamaps(0, 0, alphamapWidth, alphamapHeight);
        for (int y = 0; y < alphamapHeight; y++)
            for (int x = 0; x < alphamapWidth; x++)
                for (int l = 0; l < textureLayerCount; l++)
                    cachedSplatmaps[(x + y * alphamapWidth) * textureLayerCount + l] = splatmaps[x, y, l];
        
        // Cache slope data
        if (useAccurateSlope && slopeCache != null)
        {
            cachedSlopes = new NativeArray<float>(heightMapWidth * heightMapHeight, Allocator.TempJob);
            for (int y = 0; y < heightMapHeight; y++)
                for (int x = 0; x < heightMapWidth; x++)
                    cachedSlopes[y * heightMapWidth + x] = slopeCache.SlopesDegrees[x, y];
        }
        else cachedSlopes = new NativeArray<float>(0, Allocator.TempJob);
        
        // Cache curvature data
        if (useAccurateCurvature && curvatureCache != null)
        {
            int curvatureSize = heightMapWidth * heightMapHeight;
            cachedCurvatureStandard = new NativeArray<float>(curvatureSize, Allocator.TempJob);
            cachedCurvatureProfile = new NativeArray<float>(curvatureSize, Allocator.TempJob);
            cachedCurvaturePlan = new NativeArray<float>(curvatureSize, Allocator.TempJob);
            for (int y = 0; y < heightMapHeight; y++)
                for (int x = 0; x < heightMapWidth; x++)
                {
                    int idx = y * heightMapWidth + x;
                    cachedCurvatureStandard[idx] = curvatureCache.StandardNormalized[y, x];
                    cachedCurvatureProfile[idx] = curvatureCache.ProfileNormalized[y, x];
                    cachedCurvaturePlan[idx] = curvatureCache.PlanNormalized[y, x];
                }
        }
        else
        {
            cachedCurvatureStandard = new NativeArray<float>(0, Allocator.TempJob);
            cachedCurvatureProfile = new NativeArray<float>(0, Allocator.TempJob);
            cachedCurvaturePlan = new NativeArray<float>(0, Allocator.TempJob);
        }
        
        // Cache water shoreline distance data
        if (waterCache != null)
        {
            int waterSize = heightMapWidth * heightMapHeight;
            cachedWaterShoreDistances = new NativeArray<float>(waterSize, Allocator.TempJob);
            for (int y = 0; y < heightMapHeight; y++)
                for (int x = 0; x < heightMapWidth; x++)
                    cachedWaterShoreDistances[y * heightMapWidth + x] = waterCache.ShorelineDistances[y, x];
        }
        else cachedWaterShoreDistances = new NativeArray<float>(0, Allocator.TempJob);
        
        // Helper to create a DecorateJob with common params
        DecorateJob CreateJob(NativeArray<RuleData> rd, NativeArray<int> lro, NativeArray<int> lrc,
            NativeArray<int> li, NativeArray<bool> la, NativeArray<float> arm,
            NativeArray<int> rmo, NativeArray<int> rms, NormalizationMode nm)
        {
            return new DecorateJob
            {
                alphamapWidth = alphamapWidth, alphamapHeight = alphamapHeight,
                heightMapWidth = heightMapWidth, heightMapHeight = heightMapHeight,
                textureLayerCount = textureLayerCount, fallOffDistance = fallOffDistance,
                normMode = nm, visibilityThreshold = visibilityThreshold,
                useAccurateSlope = useAccurateSlope, cellSizeX = cellSizeX, cellSizeY = cellSizeY,
                heightScale = heightScale, slopeInDegrees = slopeInDegrees,
                useAccurateCurvature = useAccurateCurvature, cellSize = cellSize,
                curvatureNormalized = curvatureNormalized,
                waterLevel = waterLevel, terrainY = transform.position.y,
                waterShoreDistances = cachedWaterShoreDistances,
                heights = cachedHeights, slopes = cachedSlopes,
                curvatureStandard = cachedCurvatureStandard,
                curvatureProfile = cachedCurvatureProfile,
                curvaturePlan = cachedCurvaturePlan,
                existingSplatmaps = cachedSplatmaps,
                ruleData = rd, layerRuleOffsets = lro, layerRuleCounts = lrc,
                layerIndices = li, layerActive = la, allRuleMaps = arm,
                ruleMapOffsets = rmo, ruleMapSizes = rms, outputSplatmap = outputSplatmap
            };
        }
        
        void DisposeJobArrays(NativeArray<RuleData> rd, NativeArray<int> lro, NativeArray<int> lrc,
            NativeArray<int> li, NativeArray<bool> la, NativeArray<float> arm,
            NativeArray<int> rmo, NativeArray<int> rms)
        {
            rd.Dispose(); lro.Dispose(); lrc.Dispose(); li.Dispose();
            la.Dispose(); arm.Dispose(); rmo.Dispose(); rms.Dispose();
        }
        
        // PASS 1: BASE BLOCK
        if (hasBaseLayers)
        {
            PrepareJobDataForBlock(LayerBlock.Base,
                out var rd, out var lro, out var lrc, out var li, out var la,
                out var arm, out var rmo, out var rms);
            
            var baseJob = CreateJob(rd, lro, lrc, li, la, arm, rmo, rms, normalizationMode);
            
            EditorUtility.DisplayProgressBar("Decorating", "Base block (parallel)...", 0.25f);
            var handle = baseJob.Schedule(totalPixels, jobBatchSize);
            while (!handle.IsCompleted) yield return null;
            handle.Complete();
            
            DisposeJobArrays(rd, lro, lrc, li, la, arm, rmo, rms);
        }
        
        // PASS 2: OVERLAY BLOCK - composite over base
        if (hasOverlayLayers)
        {
            bool hasVegMask = HasVegetationMask();
            
            // Run overlay layers through job to get their raw weights
            var overlayOutput = new NativeArray<float>(totalPixels * textureLayerCount, Allocator.TempJob);
            
            // Temporarily swap output target
            var savedOutput = outputSplatmap;
            
            PrepareJobDataForBlock(LayerBlock.Overlay,
                out var ord, out var olro, out var olrc, out var oli, out var ola,
                out var oarm, out var ormo, out var orms);
            
            // Create overlay job writing to overlayOutput - raw weights, no normalization
            var overlayJob = CreateJob(ord, olro, olrc, oli, ola, oarm, ormo, orms, NormalizationMode.RawPassthrough);
            overlayJob.outputSplatmap = overlayOutput;
            
            EditorUtility.DisplayProgressBar("Decorating", "Overlay block (parallel)...", 0.6f);
            var oHandle = overlayJob.Schedule(totalPixels, jobBatchSize);
            while (!oHandle.IsCompleted) yield return null;
            oHandle.Complete();
            
            // Composite overlay onto base
            EditorUtility.DisplayProgressBar("Decorating", "Compositing overlay...", 0.85f);
            
            var overlayLayerInfo = new List<(int layerIndex, float opacity, OverlayBlendMode mode)>();
            foreach (var layer in layers)
            {
                if (layer.active && layer.block == LayerBlock.Overlay && layer.layerIndex < textureLayerCount)
                    overlayLayerInfo.Add((layer.layerIndex, layer.overlayOpacity, layer.overlayBlendMode));
            }
            
            for (int pixelIndex = 0; pixelIndex < totalPixels; pixelIndex++)
            {
                int offset = pixelIndex * textureLayerCount;
                float[] baseWeights = new float[textureLayerCount];
                for (int i = 0; i < textureLayerCount; i++)
                    baseWeights[i] = outputSplatmap[offset + i];
                
                // Vegetation mask: attenuate all overlay weights at this pixel
                int px = pixelIndex % alphamapWidth;
                int py = pixelIndex / alphamapWidth;
                float vegMultiplier = hasVegMask ? (1f - GetVegetationMaskAt(px, py)) : 1f;
                
                foreach (var (layerIdx, opacity, mode) in overlayLayerInfo)
                {
                    float overlayWeight = overlayOutput[offset + layerIdx] * opacity * vegMultiplier;
                    if (overlayWeight < visibilityThreshold) continue;
                    ApplyOverlayToBaseWeights(baseWeights, layerIdx, overlayWeight, mode);
                }
                
                if (renormalizeAfterOverlay)
                {
                    float total = 0f;
                    for (int i = 0; i < textureLayerCount; i++) total += baseWeights[i];
                    if (total > 0.0001f)
                        for (int i = 0; i < textureLayerCount; i++) baseWeights[i] /= total;
                }
                
                for (int i = 0; i < textureLayerCount; i++)
                    outputSplatmap[offset + i] = baseWeights[i];
            }
            
            overlayOutput.Dispose();
            DisposeJobArrays(ord, olro, olrc, oli, ola, oarm, ormo, orms);
        }
        
        // Copy results to terrain
        EditorUtility.DisplayProgressBar("Decorating", "Applying results...", 0.9f);
        map = new float[alphamapWidth, alphamapHeight, textureLayerCount];
        for (int y = 0; y < alphamapHeight; y++)
            for (int x = 0; x < alphamapWidth; x++)
                for (int l = 0; l < textureLayerCount; l++)
                    map[x, y, l] = outputSplatmap[(x + y * alphamapWidth) * textureLayerCount + l];
        
        t.terrainData.SetAlphamaps(0, 0, map);
    }
    
