    private void ProcessRuleMap(Rules rule, float[,] layer, int targetWidth, int targetHeight)
    {
        int layerWidth = layer.GetLength(0);
        int layerHeight = layer.GetLength(1);
        
        rule.map = new Color[targetWidth * targetHeight];

        if (targetWidth != layerWidth || targetHeight != layerHeight)
        {
            float ratioX = (layerWidth - 1) / (float)targetWidth;
            float ratioY = (layerHeight - 1) / (float)targetHeight;

            for (int y = 0; y < targetHeight; y++)
            {
                int yy = Mathf.FloorToInt(y * ratioY);
                float yLerp = y * ratioY - yy;
                
                for (int x = 0; x < targetWidth; x++)
                {
                    int xx = Mathf.FloorToInt(x * ratioX);
                    float xLerp = x * ratioX - xx;

                    float bl = layer[xx, yy];
                    float br = (xx + 1 < layerWidth) ? layer[xx + 1, yy] : bl;
                    float tl = (yy + 1 < layerHeight) ? layer[xx, yy + 1] : bl;
                    float tr = (xx + 1 < layerWidth && yy + 1 < layerHeight) ? layer[xx + 1, yy + 1] : bl;

                    float val = Mathf.Lerp(Mathf.Lerp(bl, br, xLerp), Mathf.Lerp(tl, tr, xLerp), yLerp);
                    rule.map[x + y * targetWidth] = new Color(val, val, val, 1f);
                }
            }
        }
        else
        {
            for (int y = 0; y < targetHeight; y++)
            {
                for (int x = 0; x < targetWidth; x++)
                {
                    float val = layer[x, y];
                    rule.map[x + y * targetWidth] = new Color(val, val, val, 1f);
                }
            }
        }
    }
    
