    /// <summary>
    /// Bake the vegetation mask texture into a flat float array at alphamap resolution.
    /// Call once before overlay compositing during Decorate().
    /// </summary>
    private void BakeVegetationMask()
    {
        cachedVegetationMask = null;
        if (!HasVegetationMask()) return;
        
        int totalPixels = alphamapWidth * alphamapHeight;
        cachedVegetationMask = new float[totalPixels];
        
        // Read texture pixels
        Color[] pixels = vegetationMaskTexture.GetPixels();
        int texW = vegetationMaskTexture.width;
        int texH = vegetationMaskTexture.height;
        
        for (int y = 0; y < alphamapHeight; y++)
        {
            for (int x = 0; x < alphamapWidth; x++)
            {
                // Sample texture with bilinear-ish nearest lookup
                float u = x / (float)(alphamapWidth - 1);
                float v = y / (float)(alphamapHeight - 1);
                int tx = Mathf.Clamp(Mathf.FloorToInt(u * (texW - 1)), 0, texW - 1);
                int ty = Mathf.Clamp(Mathf.FloorToInt(v * (texH - 1)), 0, texH - 1);
                
                Color c = pixels[tx + ty * texW];
                float val = vegetationMaskChannel switch
                {
                    ImageChannel.r => c.r,
                    ImageChannel.g => c.g,
                    ImageChannel.b => c.b,
                    ImageChannel.a => c.a,
                    _ => c.r
                };
                
                if (vegetationMaskInvert) val = 1f - val;
                
                cachedVegetationMask[x + y * alphamapWidth] = val * vegetationMaskStrength;
            }
        }
        
        Debug.Log($"[MBTerrainDecorator] Vegetation mask baked: {texW}x{texH} → {alphamapWidth}x{alphamapHeight}, channel={vegetationMaskChannel}, strength={vegetationMaskStrength}");
    }
    
